/** Tip order: shuffled slop with real tips sprinkled in, wildlife note early. */
export function tipSequence(): string[] {
  const slop = shuffle([...SLOP_TIPS]);
  const real = shuffle([...REAL_TIPS]);
  const out: string[] = [];
  let r = 0;
  for (let i = 0; i < slop.length; i++) {
    out.push(slop[i]);
    if (i % 2 === 1 && r < real.length) out.push(real[r++]);
    if (i === 2) out.push(WILDLIFE_TIP);
  }
  while (r < real.length) out.push(real[r++]);
  return out;
}

