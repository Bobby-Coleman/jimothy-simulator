/** Combo-end shouts by combo size. */
export function comboWord(combo: number): string {
  const tiers: [number, string[]][] = [
    [20, ['LEGENDARY BALL!', 'CITY COUNCIL IS CONCERNED!', 'HONORARY DEGREE IN CHAOS!']],
    [12, ['CERTIFIED CRYPTID!', 'MAXIMUM ROUNDNESS!', 'WHAT AM I LOOKING AT?!']],
    [8, ['RACCOONTASTIC!', 'TRASH-TACULAR!', 'UNHINGED!']],
    [5, ['STRIKE!', 'ROUND-TASTIC!', 'SPLENDID!']],
    [0, ['NICE!', 'NEAT!', 'OKAY THEN!']],
  ];
  for (const [min, words] of tiers) if (combo >= min) return words[Math.floor(Math.random() * words.length)];
  return 'NICE!';
}

